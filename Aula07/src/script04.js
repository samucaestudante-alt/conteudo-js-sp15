// Exercício 4: Divisão de valores informados pelo usuário

alert("Divisão de Valores Informados");

let valor1 = parseFloat(prompt("Informe o primeiro valor: "));

let valor2 = parseFloat(prompt("Informe o segundo valor: "));

let resultadoDivisão = valor1 / valor2;

alert("O resultado da soma dos valores informados é: " + resultadoDivisão);