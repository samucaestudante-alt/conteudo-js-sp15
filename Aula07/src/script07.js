// Exerciício: Calculando área da circunferência.

alert("Área da Circunferência");

let pi = 3.14;

let raioCirculo = parseFloat(prompt("Informe o raio do círculo: "));

let areaCirculo1 = raioCirculo * raioCirculo;

let areaCirculo2 = pi * areaCirculo1;

alert("A área total do círculo é " + areaCirculo2);